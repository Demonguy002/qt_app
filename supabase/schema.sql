-- Quant Aptitude Coach: run this once in Supabase SQL Editor.
-- Uses Supabase Auth for identity and Row Level Security for private records.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null,
  target_exam text,
  goal text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.practice_days (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  practice_date date not null,
  level text not null check (level in ('beginner', 'intermediate', 'pro')),
  topic_id integer,
  question_count integer not null default 4 check (question_count = 4),
  correct_count integer not null default 0,
  known_count integer not null default 0,
  total_seconds numeric(10,1) not null default 0,
  streak_value integer not null default 0,
  longest_streak integer not null default 0,
  session_json jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (user_id, practice_date)
);

create index if not exists practice_days_user_date_idx
  on public.practice_days (user_id, practice_date desc);

alter table public.profiles enable row level security;
alter table public.practice_days enable row level security;

-- A signed-in learner can read and change only their own profile.
drop policy if exists "profile_select_own" on public.profiles;
create policy "profile_select_own" on public.profiles
  for select to authenticated using (auth.uid() = id);

drop policy if exists "profile_insert_own" on public.profiles;
create policy "profile_insert_own" on public.profiles
  for insert to authenticated with check (auth.uid() = id);

drop policy if exists "profile_update_own" on public.profiles;
create policy "profile_update_own" on public.profiles
  for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

-- A signed-in learner can read and write only their own practice history.
drop policy if exists "practice_days_select_own" on public.practice_days;
create policy "practice_days_select_own" on public.practice_days
  for select to authenticated using (auth.uid() = user_id);

drop policy if exists "practice_days_insert_own" on public.practice_days;
create policy "practice_days_insert_own" on public.practice_days
  for insert to authenticated with check (auth.uid() = user_id);

drop policy if exists "practice_days_update_own" on public.practice_days;
create policy "practice_days_update_own" on public.practice_days
  for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "practice_days_delete_own" on public.practice_days;
create policy "practice_days_delete_own" on public.practice_days
  for delete to authenticated using (auth.uid() = user_id);
